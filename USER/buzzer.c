void Buzzer_SetFreq(uint16_t freq)
{
    uint32_t period;
    if (freq == 0)  // ???0???
    {
        TIM_SetCompare1(TIM2, 0);
        return;
    }

    // ?????500kHz???=500000/??(????,????1MHz)
    period = 500000 / freq;

    // ??????(????,????????????1kHz~5kHz)
    if(period > 65535) period = 65535;  // ?????????~7.6Hz(??,????)
    if(period < 100) period = 100;      // ?????????5kHz(?????)

    // ????????(50%???,??????????)
    TIM_SetAutoreload(TIM2, period - 1);
    TIM_SetCompare1(TIM2, period / 2);
}

